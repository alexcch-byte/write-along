package com.writealong.app

import com.writealong.app.glyph.CursiveGlyphs
import com.writealong.app.glyph.Glyph
import com.writealong.app.glyph.Glyphs
import com.writealong.app.glyph.Script
import com.writealong.app.glyph.sampleSegments
import com.writealong.app.practice.Assignments
import org.junit.Test
import java.io.File
import java.util.Locale

/**
 * Writes the letter shapes and assignments used by the web version to docs/js/data.js,
 * so the website and the Android app teach exactly the same letters.
 * Runs with the normal unit tests: gradlew :app:testDebugUnitTest
 */
class WebDataExport {

    private fun f(v: Float) = String.format(Locale.US, "%.1f", v).removeSuffix(".0")

    private fun str(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

    private fun glyphJson(g: Glyph): String {
        val sb = StringBuilder("{\"s\":[")
        g.strokes.forEachIndexed { i, s ->
            if (i > 0) sb.append(',')
            val pts = s.sample()
            sb.append("{\"p\":[").append(pts.joinToString(",") { "${f(it.x)},${f(it.y)}" }).append("]")
            if (s.isDot) sb.append(",\"d\":1")
            sb.append(",\"t\":").append(str(g.instruction(i))).append('}')
        }
        sb.append(']')
        if (g.leadIn) {
            val first = g.strokes[0]
            val leadEnd = sampleSegments(listOf(first.segs[0])).size - 1
            val c2 = (first.segs[0] as? com.writealong.app.glyph.Cubic)?.c2 ?: first.segs[0].end
            sb.append(",\"lead\":{\"i\":$leadEnd,\"c2\":[${f(c2.x)},${f(c2.y)}]}")
        }
        g.exit?.let { e ->
            val t = g.exitTangent!!
            sb.append(",\"exit\":[${f(e.x)},${f(e.y)}],\"tan\":[${String.format(Locale.US, "%.3f", t.x)},${String.format(Locale.US, "%.3f", t.y)}]")
        }
        sb.append('}')
        return sb.toString()
    }

    @Test
    fun exportForWeb() {
        val sb = StringBuilder()
        sb.append("// Generated by app/src/test/.../WebDataExport.kt from the Android letter data. Do not edit by hand.\n")
        sb.append("window.WA_DATA = {\n\"slant\":${CursiveGlyphs.SLANT},\n\"calSlant\":${com.writealong.app.glyph.CalligraphyGlyphs.SLANT},\n\"glyphs\":{\n")
        Script.entries.forEachIndexed { si, script ->
            if (si > 0) sb.append(",\n")
            sb.append("\"${script.name.lowercase()}\":{\n")
            val all = Glyphs.lowercase + Glyphs.uppercase
            all.forEachIndexed { i, ch ->
                if (i > 0) sb.append(",\n")
                sb.append("\"$ch\":").append(glyphJson(Glyphs.require(script, ch)))
            }
            sb.append("\n}")
        }
        sb.append("\n},\n\"assignments\":[\n")
        Assignments.list.forEachIndexed { i, a ->
            if (i > 0) sb.append(",\n")
            sb.append("{\"id\":${str(a.id)},\"title\":${str(a.title)},\"emoji\":${str(a.emoji)},")
            sb.append("\"script\":${str(a.script.name.lowercase())},\"kind\":${str(a.kind.name.lowercase())},")
            sb.append("\"items\":[${a.items.joinToString(",") { str(it) }}]}")
        }
        sb.append("\n]\n};\n")
        val out = File("../docs/js/data.js")
        out.parentFile.mkdirs()
        out.writeText(sb.toString())
        println("Web data: ${out.canonicalPath} (${out.length() / 1024} KB)")
    }
}
